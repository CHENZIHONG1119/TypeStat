//! 精确字符数的来源适配器。
//!
//! 全局钩子只能数**按键次数**，数不出"一次按键打出了几个字符"——
//! 打一个汉字可能是 1 次按键（输入法上屏），也可能是 5 次（拼音逐个敲）。
//! 要拿到精确字数，必须问应用自己。
//!
//! 两条通路，按可靠性排序：
//! 1. **`ipc`** —— 编辑器插件主动上报。走应用自己的编辑 API，精确到增删字符数，
//!    且不受无障碍/UIA 限制。WPS（`wps`）和 Obsidian 都走这条：WPS 加载项装在
//!    WPS 自己的加载项目录里，Obsidian 插件装在库的 `.obsidian/plugins` 里。
//! 2. **`uia`** —— UI Automation 采样（P2，尚未实现）。用于 Word/浏览器这类
//!    没法装插件的应用，精度和延迟都差一截。
//!
//! 这两个插件跑在**别的进程**里，程序管不着它们的死活；`ipc` 那个本地接收端
//! 是唯一的接缝（含令牌校验）。`wps` 这一支只管**把加载项装进去**，
//! 装完之后它和程序之间只剩 HTTP 上报这一条线。

pub mod ipc;
pub mod wps;
