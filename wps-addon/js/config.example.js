/*
 * TypeStat 上报配置。
 *
 * 下面两处的真值由 TypeStat 自己填进来：端口是接收端这次实际监听的
 * （42180–42189 里第一个空闲的），令牌是启动时随机生成的。手动填也行，
 * 两个值在 TypeStat 的「**适配器**」页都能看到、也能复制。
 *
 * 仓库里保存的是**没填过的那一份**，叫 config.example.js；填好之后叫
 * config.js，它不进版本库——对每台机器都不一样，而且里面有令牌。
 * 所以这份文本**永远不该出现真的令牌**。
 *
 * 如果下面 port 或 token 那两行还写着 __ 包起来的下划线占位符，说明你手上
 * 这份是模板本身，填掉它才能用：
 *     copy js\config.example.js js\config.js
 *
 * 一份文本担两个身份（模板 + 成品）是故意的：模板内嵌在程序里和这里是同一份
 * 文本，两份迟早会漂移，而照着旧的那份手填的人会得到一个连不上的加载项，
 * 且完全看不出哪里错了。
 *
 * 改完必须**重启 WPS** 才生效——加载项页面只在 WPS 启动时加载一次。
 * 在 TypeStat 里重新生成令牌后，要在「适配器」页点一下「重新装一次」，
 * 否则上报会被拒（HTTP 401），而表现是「字数一直是 0」。
 */
var TYPESTAT_CONFIG = {
  // TypeStat 本地接收端监听的端口。具体是哪个由启动时决定：
  // 在 42180–42189 里挑第一个空闲的，所以机器上跑着别的实例时会变。
  port: __PORT__,

  // 接收端令牌。TypeStat「设置」页可以看到，也可以重新生成。
  token: "__TOKEN__",

  /*
   * 上报时用的应用名。
   *
   * 必须和键盘钩子看到的进程名一致，否则同一个 WPS 会被拆成两行统计
   * （一行只有按键数，一行只有字数）。本机上 WPS 文字的进程名实测是 wps.exe。
   * 接收端会自己补 .exe 后缀并做清洗，这里写成 "wps" 也行。
   */
  app: "wps.exe",
};
